"""vLLM reasoning-parser plugins ``lfm_thinking`` and ``qwen3_8_thinking`` for the refinement loop."""

# Loaded by vLLM as a reasoning-parser plugin; it registers "lfm_thinking" and
# "qwen3_8_thinking" (<think> ... </think>).  ``enable_thinking`` is read from
# ``chat_template_kwargs`` in the per-request ``reasoning_parser_kwargs``.
from __future__ import annotations

from collections.abc import Sequence
from typing import TYPE_CHECKING

from vllm.entrypoints.openai.engine.protocol import DeltaMessage
from vllm.reasoning import ReasoningParserManager
from vllm.reasoning.basic_parsers import BaseThinkingReasoningParser

if TYPE_CHECKING:
    from vllm.entrypoints.openai.chat_completion.protocol import (
        ChatCompletionRequest,
    )
    from vllm.entrypoints.openai.responses.protocol import ResponsesRequest
    from vllm.tokenizers import TokenizerLike


class LFMThinkingParser(BaseThinkingReasoningParser):
    """Parse reasoning content emitted by LFM checkpoints.

    This parser supports LFM chat templates that delimit internal reasoning
    with ``<think>`` and ``</think>`` tokens.

    Text inside the delimiters is exposed as reasoning, while text following
    ``</think>`` is exposed as normal assistant response content.

    The ``enable_thinking`` chat-template argument controls how output without
    a closing ``</think>`` token is interpreted:

    - If thinking is enabled, unterminated output is treated as reasoning.
    - If thinking is disabled, unterminated output is treated as normal
      response content.

    Both complete and streaming model outputs are supported.
    """

    def __init__(
        self,
        tokenizer: "TokenizerLike",
        *args,
        **kwargs,
    ):
        """Initialize the LFM reasoning parser.

        Args:
            tokenizer: Tokenizer used by the model and reasoning parser.
            *args: Additional positional arguments forwarded to the base
                reasoning parser.
            **kwargs: Additional keyword arguments forwarded to the base
                reasoning parser. ``chat_template_kwargs`` may contain
                ``enable_thinking`` to control how unterminated output is
                interpreted.

        Notes:
            ``enable_thinking`` defaults to ``True`` when it is not explicitly
            provided through ``chat_template_kwargs``.
        """
        super().__init__(tokenizer, *args, **kwargs)

        chat_kwargs = kwargs.get("chat_template_kwargs", {}) or {}
        self.thinking_enabled = chat_kwargs.get("enable_thinking", True)

    @property
    def start_token(self) -> str:
        """Return the token marking the beginning of reasoning content."""
        return "<think>"

    @property
    def end_token(self) -> str:
        """Return the token marking the end of reasoning content."""
        return "</think>"

    def extract_reasoning(
        self,
        model_output: str,
        request: "ChatCompletionRequest | ResponsesRequest",
    ) -> tuple[str | None, str | None]:
        """Extract reasoning and response content from complete model output.

        An optional leading ``<think>`` token is removed before parsing.

        If ``</think>`` is present, text before it is returned as reasoning and
        text after it is returned as normal response content.

        If no closing token is present, interpretation depends on
        ``enable_thinking``:

        - When enabled, the complete output is returned as reasoning.
        - When disabled, the complete output is returned as response content.

        Args:
            model_output: Complete text generated by the model.
            request: Request associated with the generation. It is accepted to
                satisfy the vLLM reasoning-parser interface but is not inspected
                directly by this implementation.

        Returns:
            A ``(reasoning, content)`` tuple. Either value may be ``None`` when
            the corresponding portion is absent.
        """
        model_output_parts = model_output.partition(self.start_token)
        model_output = (
            model_output_parts[2] if model_output_parts[1] else model_output_parts[0]
        )

        if self.end_token not in model_output:
            if not self.thinking_enabled:
                return None, model_output

            return model_output, None

        reasoning, _, content = model_output.partition(self.end_token)

        return reasoning, content or None

    def extract_reasoning_streaming(
        self,
        previous_text: str,
        current_text: str,
        delta_text: str,
        previous_token_ids: Sequence[int],
        current_token_ids: Sequence[int],
        delta_token_ids: Sequence[int],
    ) -> DeltaMessage | None:
        """Parse a streaming delta into reasoning and response content.

        The method detects the ``<think>`` and ``</think>`` boundaries using
        the token IDs provided by vLLM.

        Text produced before ``</think>`` is emitted through
        ``DeltaMessage.reasoning``. Text produced after ``</think>`` is emitted
        through ``DeltaMessage.content``.

        If the closing reasoning token and normal response content occur in the
        same streaming delta, both fields are populated in the returned
        ``DeltaMessage``.

        Delimiter tokens themselves are removed from emitted output.

        Args:
            previous_text: Full generated text before the current update.
            current_text: Full generated text including the current update.
            delta_text: Text introduced by the current streaming update.
            previous_token_ids: Token IDs generated before the current update.
            current_token_ids: Token IDs generated through the current update.
            delta_token_ids: Token IDs introduced by the current update.

        Returns:
            A ``DeltaMessage`` containing newly extracted reasoning and/or
            response content, or ``None`` when the current delta contains
            nothing that should be emitted.
        """
        if self.start_token_id in delta_token_ids:
            start_idx = delta_text.find(self.start_token)

            if start_idx >= 0:
                delta_text = delta_text[start_idx + len(self.start_token) :]

        if self.end_token_id in delta_token_ids:
            end_idx = delta_text.find(self.end_token)

            if end_idx >= 0:
                reasoning = delta_text[:end_idx]
                content = delta_text[end_idx + len(self.end_token) :]

                if not reasoning and not content:
                    return None

                return DeltaMessage(
                    reasoning=reasoning or None,
                    content=content or None,
                )

            return None

        if not delta_text:
            return None

        if self.end_token_id in previous_token_ids:
            return DeltaMessage(content=delta_text)

        return DeltaMessage(reasoning=delta_text)


ReasoningParserManager.register_module(
    ["lfm_thinking", "qwen3_8_thinking"],
    module=LFMThinkingParser,
)
